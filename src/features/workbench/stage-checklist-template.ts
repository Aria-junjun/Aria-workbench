export function getStageMeta(stage: ProductLifecycleStage) {
  return stageMeta[stage];
}

export function getDefaultChecklist(stage: ProductLifecycleStage): StageChecklistItem[] {
  return stageChecklistItems[stage].map((item) => ({ ...item }));
}

export function getAllStages(): ProductLifecycleStage[] {
  return [...PRODUCT_LIFECYCLE_STAGES];
}

export function getStageIndex(stage: ProductLifecycleStage): number {
  return PRODUCT_LIFECYCLE_STAGES.indexOf(stage);
}

export function getNextStage(current: ProductLifecycleStage): ProductLifecycleStage | null {
  const idx = getStageIndex(current);
  if (idx === -1 || idx >= PRODUCT_LIFECYCLE_STAGES.length - 1) return null;
  return PRODUCT_LIFECYCLE_STAGES[idx + 1];
}

export function getPrevStage(current: ProductLifecycleStage): ProductLifecycleStage | null {
  const idx = getStageIndex(current);
  if (idx <= 0) return null;
  return PRODUCT_LIFECYCLE_STAGES[idx - 1];
}
